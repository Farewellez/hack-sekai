# Successive Powers
# ==================================================================================
# IMPORTED LIBRARY
# ==================================================================================
from math import gcd

# ===================================
# KNOWN VARIABLES
# y = {588,665,216,113,642,4,836,114,851,492,819,237}
# 
# UNKNOWN VARIABLES
# x    = integer
# p    = modulo (3 digits) 
# 
# REFERENCES:
# https://math.stackexchange.com/questions/1952453/finding-an-integer-x-and-a-3-digit-prime-p-that-solves-the-problem
# https://share.google/aimode/GZR1QUmqaDoL3xykd
# ===================================
y = [588,665,216,113,642,4,836,114,851,492,819,237]

# ============================================================================================================================================
# FIND x (mod p)
# 
# KNOWN EQUATIONS:
# -> y_1.x = y_2 mod p
# -> y_3.x = y_2 mod p 
# 
# SUBTITUTION:
# y_1 = x^k
# y_2 = x^(k + 1)
# y_3 = x^(k + 2)
# 
# -> y_1 . y_3 = x^k . x^(k + 2)
# -> y_1 . y_3 = x^(2k + 2)
# 
# IN ANOTHER UNIVERSE:
# y_2 = x^(k + 1)
# y_2^2 = (x^(k + 1))^2
# y_2^2 = x^(2k + 2) mod p
# 
# THEREFORE:
# y_1 . y_3 - y_2^2 = multiple of p
# ============================================================================================================================================
T1 = (y[0] * y[2]) - pow(y[1], 2)
T2 = (y[1] * y[3]) - pow(y[2], 2)
print(f" T1 : {T1}")
if T1 < 0:
    print(f"|T1|: {abs(T1)}")
print(f" T2 : {T2}")

# ============================================================================================================================================
# FINDING P
# using gcd formula:
# p = gcd(T1, T2)
# ============================================================================================================================================
p = gcd(T1, T2)
print(f" p  : {p}")

# ============================================================================================================================================
# RECOVER X
# using modular inverse formula:
# y_1.x = y_2 mod p
# x     = y_2.y_1^-1 mod p
# ============================================================================================================================================
x = y[1]*pow(y[0],-1,p) % p
print(f" x  : {x}")

# ============================================================================================================================================
# PRINT OUT THE FLAG
# crypto{p,x}
# ============================================================================================================================================
flag = "crypto{"+str(p)+","+str(x)+"}"
print(f"Flag: {flag}")